#!/usr/bin/env node
/* tools/shim.mjs — build plugins/pandoc-export/wasi-shim.js from @bjorn3/browser_wasi_shim.
 *
 *   npm run shim
 *
 * A plugin is loaded from a `blob:` URL, so it cannot `import` anything: no bare specifier,
 * no relative path. The WASI shim is ESM only because that is how it is published — inside it
 * is five small files of plain classes — so this wraps each file in an IIFE, in dependency
 * order, and re-exports the handful of names the glue needs. The artifact is committed because
 * the plugin must be a self-contained file at a pinned URL; the command is committed so nobody
 * has to trust it.
 *
 * `--check` fails when the artifact is stale, which is what `npm run check` runs.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, "../node_modules/@bjorn3/browser_wasi_shim/dist");
const OUT = path.join(HERE, "../plugins/pandoc-export/wasi-shim.js");

/* Dependency order, read off the imports: wasi_defs has none, wasi depends on both. */
const MODULES = [
  ["wasi_defs", "wasi_defs.js"],
  ["debug", "debug.js"],
  ["fd", "fd.js"],
  ["fs_mem", "fs_mem.js"],
  ["wasi", "wasi.js"],
];

function wrap(name, file) {
  let code = fs.readFileSync(path.join(SRC, file), "utf8");
  const exported = new Map();
  let defaultLocal = null;
  /* Module variables are prefixed: wasi.js imports `debug` from debug.js, and
     `const {debug} = debug` is a TDZ error that fails at load, not at run. */
  const mod = (from) => `M_${path.basename(from, ".js")}`;

  code = code.replace(/import\s*\*\s*as\s*(\w+)\s*from\s*"([^"]+)";?/g,
    (_, local, from) => `const ${local} = ${mod(from)};`);
  code = code.replace(/import\s*\{([^}]+)\}\s*from\s*"([^"]+)";?/g, (_, names, from) => {
    const bound = names.split(",").map((n) => n.trim()).filter(Boolean)
      .map((n) => n.replace(/\s+as\s+/, ": ")).join(", ");
    return `const { ${bound} } = ${mod(from)};`;
  });
  code = code.replace(/import\s+(\w+)\s+from\s*"([^"]+)";?/g,
    (_, local, from) => `const ${local} = ${mod(from)}.default;`);
  code = code.replace(/export\s+(class|const|let|var|function)\s+([A-Za-z_$][\w$]*)/g,
    (_, kind, id) => { exported.set(id, id); return `${kind} ${id}`; });
  code = code.replace(/export\s*\{([^}]+)\};?/g, (_, names) => {
    for (const part of names.split(",").map((s) => s.trim()).filter(Boolean)) {
      const [local, alias] = part.split(/\s+as\s+/);
      if (alias === "default") defaultLocal = local;
      else exported.set(local, alias || local);
    }
    return "";
  });
  code = code.replace(/export\s+default\s+/g, () => {
    defaultLocal = defaultLocal || "__default";
    return `const ${defaultLocal} = `;
  });

  const pairs = [...exported].map(([local, alias]) => (local === alias ? local : `${alias}: ${local}`));
  if (defaultLocal) pairs.push(`default: ${defaultLocal}`);
  return `/* ${file} */\nconst M_${name} = (() => {\n${code}\nreturn {${pairs.join(", ")}};\n})();`;
}

const built = `/*! @bjorn3/browser_wasi_shim 0.4.2 | MIT OR Apache-2.0
 *  https://github.com/bjorn3/browser_wasi_shim
 *  Bundled as one ES module for the pandoc-export plugin, which is loaded from a blob: URL
 *  and therefore cannot import anything. Generated by tools/shim.mjs — do not edit. */
${MODULES.map(([name, file]) => wrap(name, file)).join("\n\n")}

export const WASI = M_wasi.default;
export const WASIProcExit = M_wasi.WASIProcExit;
export const Fd = M_fd.Fd;
export const Inode = M_fd.Inode;
export const File = M_fs_mem.File;
export const Directory = M_fs_mem.Directory;
export const OpenFile = M_fs_mem.OpenFile;
export const PreopenDirectory = M_fs_mem.PreopenDirectory;
export const ConsoleStdout = M_fs_mem.ConsoleStdout;
export const wasi = M_wasi_defs;
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== built) {
    console.error("shim: plugins/pandoc-export/wasi-shim.js is stale — run: npm run shim");
    process.exit(1);
  }
  console.log("shim: ok");
} else {
  fs.mkdirSync(path.dirname(OUT), {recursive: true});
  fs.writeFileSync(OUT, built);
  console.log(`shim: plugins/pandoc-export/wasi-shim.js (${(built.length / 1024).toFixed(1)} KB)`);
}
